function AuthGate() {
  const { user, loading } = useAuth();
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setMounted(true);
  }, []);

  if (!mounted || loading) {
    return (
      <div
        className="min-h-screen flex items-center justify-center"
        style={{ background: "#080D0A" }}
      >
        <div className="flex flex-col items-center gap-4">
          <div
            className="w-12 h-12 rounded-xl flex items-center justify-center text-2xl animate-pulse"
            style={{ background: "linear-gradient(135deg, #15803D, #4ADE80)" }}
          >
            ∞
          </div>
          <p className="text-[#647067] text-sm">جاري التحميل...</p>
        </div>
      </div>
    );
  }

  if (!user) {
    return <AuthPage onSuccess={() => {}} />;
  }

  return (
    <AppShell>
      <Outlet />
    </AppShell>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <ThemeProvider>
        <DirectionProvider>
          <AuthProvider>
            <AuthGate />
          </AuthProvider>
        </DirectionProvider>
      </ThemeProvider>
    </QueryClientProvider>
  );
}
